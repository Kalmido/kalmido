#!/usr/bin/env python3
"""Decisions against patching, held as rules with their reason and the right way (#7143, the findings of audit #5501).

A fix that was decided once ("one IBAN check", "the environment through core/env.py") is undone by the next package that
does not know it. Where the decision can be seen in the text of the code, it stands here as a rule: a pattern, why it is
wrong, what to use instead. The places of today stand per rule and file in tools/rules_baseline.json; a rule's TOTAL only
falls (moving code between files is no finding), --update lowers it (never raises, never adds a rule). The clean-up of the
places of today runs through the tasks named per rule, not through this check.

Rules (RULES below; sharp = a rise is red, otherwise a notice until the task that brings the right way is done):
  env            os.environ / os.getenv in the server code outside kalmido/core/env.py                    (#7156)
  version-mark   a version mark "2.<n>[.<n>] (#<n>)" in kalmido/ and the client code, notice only: the total
                 moves with every package merged meanwhile; red is an ADDED line with a mark (tools/pr_lint.py marks) (#7156)
  mcp-dup        a top-level function / class name defined in two starter files mcp/*.py                  (#7151)
  mcp-fence      a call of _data_fence() in the starter files: the fence belongs into handle() once        (#7151)
  starter-secret alternatives of the SECRET_* name patterns of the starter: a name check is no wall          (#7149)
  generated      a tracked file whose head says it is generated (dependency locks aside)                   (#6887)
  client-write   a writing api() / fetch() in static/js outside objsave.js, notice only                     (#7150)
Not built here (the right way does not exist yet, so the message could not name it): FOR UPDATE outside the lock helper
(#7153), IBAN patterns outside core/iban.py (#7154), except Exception around unseal( (#7156: unseal_or); the schema,
export, import and month lock rules (#7145 - #7148) need the structure those tasks build.

usage: python3 tools/check_rules.py [-v] [--notice] [--root DIR] [--update] [--list RULE]     exit 1 = red
Standard library only.
"""
import ast
import os
import re
import subprocess
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import lintmsg  # noqa: E402 -- tools/ is not a package; the line above puts it on the path

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BASELINE = os.path.join("tools", "rules_baseline.json")
ABOUT = "tools/check_rules.py (#7143): places per rule and file; a total only falls (--update lowers, never raises)"
SKIP_DIRS = {".git", "node_modules", "__pycache__", "vendor", ".data"}


def walk(root, top, ends):
    p = os.path.join(root, top)
    if os.path.isfile(p):
        return [top]
    out = []
    for d, dirs, names in os.walk(p):
        dirs[:] = sorted(x for x in dirs if x not in SKIP_DIRS and not x.startswith(".data"))
        out += [os.path.relpath(os.path.join(d, n), root).replace(os.sep, "/") for n in sorted(names) if n.endswith(ends)]
    return out


def read(root, rel):
    with open(os.path.join(root, rel), encoding="utf-8", errors="replace") as f:
        return f.read()


def regex_counts(root, files, rx, skip=()):
    out = {}
    for rel in files:
        if rel in skip:
            continue
        n = len(rx.findall(read(root, rel)))
        if n:
            out[rel] = n
    return out


def server_py(root):
    return walk(root, "app.py", ".py") + walk(root, "kalmido", ".py")


def client_js(root):
    sd = os.path.join(root, "static")
    top = [f"static/{n}" for n in sorted(os.listdir(sd)) if n.endswith(".js")] if os.path.isdir(sd) else []
    return top + walk(root, "static/js", ".js")


ENV = re.compile(r"\bos\.(?:environ\b|getenv\s*\()")
VERSION = re.compile(r"\b2\.\d+(?:\.\d+)?(?:\s+[A-Z]\d?)?\s*\(#\d+\)")
FENCE = re.compile(r"(?<!def )\b_data_fence\(")
WRITE = re.compile(r"\bapi\(\s*['\"](?:POST|PUT|PATCH|DELETE)['\"]|\bmethod\s*:\s*['\"](?:POST|PUT|PATCH|DELETE)['\"]")
GENERATED = re.compile(r"generated by|do not edit", re.I)


def count_env(root):
    return regex_counts(root, server_py(root), ENV, skip=("kalmido/core/env.py",))


def count_version(root):
    return regex_counts(root, server_py(root) + client_js(root), VERSION)


def mcp_files(root):
    return [f for f in walk(root, "mcp", ".py") if f.count("/") == 1]


def count_mcp_dup(root):
    """Per starter file: its top-level names that another starter file defines too."""
    names = {}
    for rel in mcp_files(root):
        try:
            tree = ast.parse(read(root, rel))
        except SyntaxError:
            continue
        for node in tree.body:
            if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)) and node.name != "main":
                names.setdefault(node.name, set()).add(rel)
    out = {}
    for _n, where in names.items():
        if len(where) > 1:
            for rel in where:
                out[rel] = out.get(rel, 0) + 1
    return out


def count_mcp_fence(root):
    return regex_counts(root, mcp_files(root), FENCE)


def count_secret(root):
    """Per starter file: the alternatives ('|' + 1 per pattern) of the SECRET_* patterns."""
    out = {}
    for rel in mcp_files(root):
        try:
            tree = ast.parse(read(root, rel))
        except SyntaxError:
            continue
        n = 0
        for node in tree.body:
            if isinstance(node, ast.Assign) and any(isinstance(t, ast.Name) and t.id.startswith("SECRET_") for t in node.targets):
                text = "".join(c.value for c in ast.walk(node.value) if isinstance(c, ast.Constant) and isinstance(c.value, str))
                n += text.count("|") + 1
        if n:
            out[rel] = n
    return out


def tracked(root):
    """The tracked files, or None without git (a tree copied without .git): the rule is left out then."""
    try:
        r = subprocess.run(["git", "-C", root, "ls-files", "-z"], capture_output=True, timeout=60)
    except (OSError, subprocess.TimeoutExpired):
        return None
    if r.returncode != 0:
        return None
    return [x for x in r.stdout.decode("utf-8", "replace").split("\0") if x]


def count_generated(root):
    files = tracked(root)
    if files is None:
        return None
    out = {}
    for rel in files:
        if "/vendor/" in f"/{rel}" or rel.endswith(".lock") or "node_modules/" in rel:
            continue  # pinned dependency locks are the input of a build, not a copy of the repo's own sources
        p = os.path.join(root, rel)
        try:
            with open(p, encoding="utf-8", errors="replace") as f:
                head = "".join(f.readline() for _ in range(5))
        except (OSError, UnicodeDecodeError):
            continue
        if GENERATED.search(head):
            out[rel] = 1
    return out


def count_client_write(root):
    return regex_counts(root, client_js(root), WRITE, skip=("static/js/objsave.js",))


# name: (counter, sharp, why, instead)
RULES = {
    "env": (count_env, True,
            "a variable read by hand has its own default and its own parsing: a non-number crashes at import, the defaults "
            "stand twice and drift (#7156)",
            "env_str / env_int / env_bool of kalmido/core/env.py, the variable declared in its VARS"),
    "version-mark": (count_version, False,
                     "the history is in git; version marks are 5 to 10 % of the lines and a source of merge conflicts (#7156)",
                     "a comment says what holds and why, without '2.<n>'; a decided task stays as '(#<id>)', the history goes into the "
                     "commit subject"),
    "mcp-dup": (count_mcp_dup, True,
                "a fix lands in one copy only (#6884: the same fix in four files); the starter files load together (#7151)",
                "one shared starter module (mcp/starter_files.txt, with its hash) - until it exists, extend the copy that is "
                "there, never add a further one"),
    "mcp-fence": (count_mcp_fence, True,
                  "a fence per tool and field misses the next tool: foreign text reaches the model without a fence (#7151)",
                  "the fence in handle() of mcp/kalmido_mcp.py for every text the server marks as foreign"),
    "starter-secret": (count_secret, True,
                       "a name match on the command text is no wall: python -c open(...) or a composed file name passes (#7149)",
                       "take the secret out of what the run can read (#7149); the SECRET_* patterns are not extended"),
    "generated": (count_generated, True,
                  "a hand-kept copy of something derived drifts and costs a follow-up commit per change (#6887)",
                  "build it during the build or serve it from the server; the generator stays the one source"),
    "client-write": (count_client_write, False,
                     "every own write path needs its own conflict protocol (#7150)",
                     "objsave.js (saveDialog) and kalmido/core/writes.py"),
}


def counts(root=ROOT, only=None):
    """{rule: {"total", "files"}}; a rule whose counter cannot run here (generated without git) is missing from skipped."""
    per, skipped = {}, []
    for name, (fn, *_r) in RULES.items():
        if only and name != only:
            continue
        c = fn(root)
        if c is None:
            skipped.append(name)
            continue
        per[name] = c
    return lintmsg.as_counts(per), skipped


def main(argv):
    root = argv[argv.index("--root") + 1] if "--root" in argv else ROOT
    if "--list" in argv:
        name = argv[argv.index("--list") + 1]
        now, _s = counts(root, name)
        for rel, n in sorted(now.get(name, {}).get("files", {}).items()):
            print(f"{rel}: {n}")
        return 0
    now, skipped = counts(root)
    path = os.path.join(root, BASELINE)
    base = lintmsg.load(path)
    if "--update" in argv:
        if skipped:
            now = {**now, **{r: base[r] for r in skipped if r in base}}
        new = lintmsg.lowered(now, base)
        lintmsg.save(path, ABOUT, new)
        print("check_rules: baseline lowered to today (" + ", ".join(f"{r} {v['total']}" for r, v in sorted(new.items())) + ")")
        base = new
    for r in skipped:
        base.pop(r, None)
        print(f"check_rules: {r} not checked here (no git)")
    # --notice (the lint job): every rise is a notice - the total moves with every package merged meanwhile; the ratchet per
    # change is tools/pr_lint.py (marks, suppress: rule env); the other rules seldom move and are red in the queue's checks
    soft = ("env",) if "--notice" in argv else ()
    rose, fell = lintmsg.compare(now, base, lambda r: RULES[r][1] and r not in soft)
    red = lintmsg.report("check_rules", rose, fell, lambda r: f"rule {r}", "python3 tools/check_rules.py --update")
    for r, _n, _b, _up, is_sharp in rose:
        if is_sharp:
            _fn, _s, why, instead = RULES[r]
            print(f"check_rules: {r}: Why: {why}")
            print(f"check_rules: {r}: Instead: {instead}")
    if red:
        print(f"check_rules: {lintmsg.NOT}")
        print("check_rules: the places per file: python3 tools/check_rules.py --list <rule>")
    if "-v" in argv or red:
        print("check_rules: " + ", ".join(f"{r} {now.get(r, {}).get('total', 0)}" for r in RULES if r not in skipped)
              + f"; {red} red rule(s)")
    return 1 if red else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
