#!/usr/bin/env python3
"""2.380 G (#3390): mcp/starter_sha256.txt -- the SHA-256 of the agent starter files (mcp/starter_files.txt and every file it
lists), one "<sha256>  <name>" line each (the sha256sum format). The server sends them in the answer of
POST /api/agent-setup/redeem (starter_sha256) and static/agent/setup.sh / setup.ps1 refuse a downloaded starter file whose hash
differs, so a changed file on the download address is never installed.
#6887: the file is no longer checked in (two packages that each changed a starter file collided in it in GitHub's merge queue):
the image build writes it (Dockerfile, stage startersha), a checkout without it computes the same sums
(kalmido/agents/setup.py ains_starter_sha), the tests call sums() here.
usage: python3 tools/starter_sha.py           write mcp/starter_sha256.txt (in .gitignore)
       python3 tools/starter_sha.py --print   print the lines instead"""
import hashlib
import os
import sys

MCP = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "mcp")
OUT = os.path.join(MCP, "starter_sha256.txt")
HEAD = "# 2.380 G (#3390): generated by tools/starter_sha.py from starter_files.txt at the image build (#6887) -- do not edit\n"


def names(mcp=MCP):
    out = ["starter_files.txt"]
    with open(os.path.join(mcp, "starter_files.txt"), encoding="utf-8") as f:
        for ln in f:
            n = ln.split("#", 1)[0].strip()
            if n and n not in out:
                out.append(n)
    return out


def sums(mcp=MCP):
    """{file name: sha256} of the starter files, in the order of starter_files.txt."""
    out = {}
    for n in names(mcp):
        with open(os.path.join(mcp, n), "rb") as f:
            out[n] = hashlib.sha256(f.read()).hexdigest()
    return out


def render(mcp=MCP):
    return HEAD + "".join(f"{h}  {n}\n" for n, h in sums(mcp).items())


def main(argv):
    if "--check" in argv:  # #6887: nothing checked in to compare with any more; kept so an older caller stays green
        print("starter_sha: --check is gone since #6887 (the image build writes the file), nothing to check")
        return 0
    want = render()
    if "--print" in argv:
        sys.stdout.write(want)
        return 0
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(want)
    print(f"starter_sha: wrote {want.count(chr(10)) - 1} hashes to mcp/starter_sha256.txt")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
